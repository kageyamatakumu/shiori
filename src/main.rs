/// # Shiori (栞)
///
/// ダウンロードフォルダ内のファイルを、ルールに基づいて指定のワークスペースへ
/// 整理・移動するためのコマンドラインツールです。
///
/// このバイナリはアプリケーションのエントリーポイントとして機能し、
/// 実行フローの制御と最終的なエラー出力（標準エラー出力）を担当します。
use anyhow::Result;
use colored::Colorize;
use shiori::application::App;

/// アプリケーションのメインエントリーポイント。
///
/// `App` インスタンスを生成し、実行フローを開始します。
///
/// # Errors
///
/// 以下の状況で `anyhow::Error` を返し、ステータスコード 1 で終了します：
/// - 設定ファイルの読み込みや初期化に失敗した場合
/// - ファイル移動中に I/O エラーが発生した場合
/// - ユーザーが意図的に処理を中断した場合
fn main() -> Result<()> {
    // アプリケーションの初期化
    // 設定の読み込みや FileOrganizer の準備を行います。
    let app = App::new()?;

    // メインロジックの実行
    // フォルダの準備、ファイル検索、ユーザー確認、移動処理を順次実行します。
    if let Err(e) = app.run() {
        // エラーメッセージを赤文字の太字で強調して表示
        eprintln!("{} {}", "Error:".red().bold(), e);
        std::process::exit(1);
    }

    Ok(())
}
